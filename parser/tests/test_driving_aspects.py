"""Tests for driving_aspects (module 20).

The synthetic laps here are generated by DISTANCE: the speed profile is a function
of where the car is, and ticks are stepped through it at 60 Hz, so a lap that
brakes later or carries more speed genuinely takes fewer ticks -- lap times
differ, which the shared fixture (fixed ticks per lap) cannot do. Two corners:
T1 braked for, T2 a flat-out kink nobody brakes for.
"""

import json

import numpy as np
import pytest

from proctor_parser import parse_ibt
from proctor_parser.analysis import driving_aspects
from tests.synthetic import build_ibt, make_core_channels

G = 9.81
L = 4000.0
RATE = 60
APEX1, APEX2 = 0.30, 0.70


def _speed(s: np.ndarray, spec: dict) -> np.ndarray:
    bp, fp, vmin = spec["brake_at"], spec["full_at"], spec["vmin"]
    knots = [0.0, bp, APEX1, fp, 0.62, APEX2, 0.78, 1.0]
    vals = [60.0, 60.0, vmin, 60.0, 60.0, spec.get("kink", 52.0), 60.0, 60.0]
    return np.interp(s, knots, vals)


def _lap_channels(spec: dict) -> dict[str, np.ndarray]:
    s_list = []
    s = 0.0
    while s < 1.0:
        s_list.append(s)
        s += float(_speed(np.array([s]), spec)[0]) / RATE / L
    s = np.array(s_list)
    v = _speed(s, spec)
    bp, fp = spec["brake_at"], spec["full_at"]

    brake = np.where((s >= bp) & (s < APEX1 - 0.006), spec.get("peak", 0.8), 0.0)
    pick = spec.get("pickup_at", APEX1 + 0.005)
    throttle = np.where(s < bp, 1.0, 0.0)
    ramp = (s >= pick) & (s < fp)
    throttle[ramp] = np.clip((s[ramp] - pick) / max(fp - pick, 1e-6), 0.05, 1.0)
    throttle[s >= fp] = 1.0
    if spec.get("lift"):
        dip = (s >= (pick + fp) / 2) & (s < (pick + fp) / 2 + 0.004)
        throttle[dip] *= 0.5

    lat = np.interp(s, [0, APEX1 - 0.025, APEX1, APEX1 + 0.03, APEX2 - 0.03, APEX2, APEX2 + 0.03, 1],
                    [0, 0, 1.5, 0, 0, -1.2, 0, 0]) * G
    dvds = np.gradient(v, s) / L
    long_acc = v * dvds
    wheel = v.copy()
    if spec.get("lockup"):
        lock = (s >= APEX1 - 0.02) & (s < APEX1 - 0.012)
        wheel = np.where(lock, v * 0.4, v)  # under the 0.5x lockup line

    # A circle of circumference L; `wide` pushes T1's exit outward in metres.
    r = L / (2 * np.pi)
    out = np.interp(s, [0, APEX1, APEX1 + 0.05, APEX1 + 0.09, 1], [0, 0, spec.get("wide", 0.0), 0, 0])
    ang = 2 * np.pi * s
    x, y = (r + out) * np.cos(ang), (r + out) * np.sin(ang)
    lat_deg = 33.80 + y / 111320.0
    lon_deg = -84.27 + x / (111320.0 * np.cos(np.radians(33.80)))
    return {
        "LapDistPct": s, "Speed": v, "BrakeRaw": brake, "Brake": brake.copy(),
        "Throttle": throttle, "LatAccel": lat, "LongAccel": long_acc,
        "SteeringWheelAngle": lat / G * 0.2, "LFspeed": wheel, "RFspeed": wheel,
        "LRspeed": v, "RRspeed": v, "VelocityX": v, "Lat": lat_deg, "Lon": lon_deg,
    }


def _session(specs: list[dict]):
    """Out lap + `specs` + a partial closing lap."""
    laps = [_lap_channels(sp) for sp in [specs[0]] + specs + [specs[0]]]
    laps[-1] = {k: v[: len(v) // 3] for k, v in laps[-1].items()}
    n = sum(len(l["Speed"]) for l in laps)
    ch = make_core_channels(n_laps=1, ticks_per_lap=n, slow_lap=None, incident_lap=None)
    lap_idx = np.concatenate([np.full(len(l["Speed"]), i, dtype=float) for i, l in enumerate(laps)])
    ch["Lap"] = lap_idx
    ch["OnPitRoad"] = (lap_idx == 0).astype(float)
    for name in laps[0]:
        ch[name] = np.concatenate([l[name] for l in laps])
    ch["YawRate"] = ch["LatAccel"] / np.maximum(ch["Speed"], 1.0)
    return parse_ibt(build_ibt(ch))[0]


BASE = dict(brake_at=0.25, full_at=0.36, vmin=25.0)


def _payload(specs):
    s = _session(specs)
    p = driving_aspects.compute(s)
    assert p.get("insufficient_data") is not True, p.get("reason")
    return s, p


def _clean_numbers(s):
    return [l.lap_number for l in s.laps if l.is_valid and not l.is_out_lap and not l.is_anomalous]


def test_zones_add_up_to_each_recorded_lap_time():
    specs = [dict(BASE, brake_at=0.25 + 0.004 * i, vmin=24 + i) for i in range(6)]
    s, p = _payload(specs)
    for lap in _clean_numbers(s):
        k = str(lap)
        total = p["lead_in"]["per_lap"][k] + sum(
            c["zones"][z]["per_lap"][k] for c in p["corners"] for z in driving_aspects.ZONES
        )
        assert total == pytest.approx(p["lap_times_s"][k], abs=1e-3)
    assert len({p["lap_times_s"][str(n)] for n in _clean_numbers(s)}) > 1, "laps really differ"


def test_braking_later_on_the_quick_laps_is_braking_time_at_stake():
    # Later braking AND a quicker lap: the shape of a driver who found a brake point.
    specs = [dict(BASE, brake_at=b) for b in (0.240, 0.246, 0.252, 0.258, 0.262, 0.266, 0.270)]
    s, p = _payload(specs)
    t1 = p["corners"][0]
    assert t1["braked_laps"] == 7
    assert t1["zones"]["braking"]["at_stake_s"] > 0.0
    bp = t1["metrics"]["brake_point_m"]
    assert bp["quick"] < bp["typical"], "the quick passes braked closer to the apex"
    assert bp["link"]["rho"] > 0.5 and bp["link"]["p"] < 0.10
    assert p["aspects"]["braking"]["at_stake_s"] >= t1["zones"]["braking"]["at_stake_s"]


def test_the_zone_starts_where_the_earliest_lap_braked():
    specs = [dict(BASE, brake_at=b) for b in (0.240, 0.250, 0.255, 0.260, 0.262)]
    s, p = _payload(specs)
    assert p["corners"][0]["bounds"]["brake_pct"] == pytest.approx(0.240, abs=0.002)


def test_a_lone_early_braker_does_not_set_the_zone():
    specs = [dict(BASE, brake_at=b) for b in (0.200, 0.250, 0.251, 0.252, 0.253, 0.254)]
    s, p = _payload(specs)
    t1 = p["corners"][0]
    assert t1["bounds"]["brake_pct"] > 0.24
    assert t1["early_brakers"] == [_clean_numbers(s)[0]]


def test_a_corner_nobody_brakes_for_has_an_empty_braking_zone():
    s, p = _payload([dict(BASE, vmin=24 + i) for i in range(5)])
    t2 = p["corners"][1]
    assert t2["braked_laps"] == 0
    assert t2["bounds"]["brake_pct"] == t2["bounds"]["turn_in_pct"]
    assert t2["zones"]["braking"]["typical_s"] == pytest.approx(0.0, abs=1e-6)


def test_earlier_throttle_on_the_quick_laps_shows_up_on_the_exit():
    picks = (0.316, 0.313, 0.310, 0.307, 0.304, 0.302)
    specs = [dict(BASE, pickup_at=pk, full_at=pk + 0.04) for pk in picks]
    s, p = _payload(specs)
    t1 = p["corners"][0]
    assert t1["zones"]["exit"]["at_stake_s"] > 0.0
    pm = t1["metrics"]["pickup_m"]
    assert pm["quick"] < pm["typical"], "quick laps picked up the throttle sooner"


def test_lockups_are_linked_time_not_billed_time():
    specs = [
        dict(BASE, vmin=22.0, lockup=True), dict(BASE, vmin=22.5, lockup=True),
        dict(BASE, vmin=22.2, lockup=True),
        dict(BASE, vmin=26.0), dict(BASE, vmin=26.5), dict(BASE, vmin=26.2),
    ]
    s, p = _payload(specs)
    link = p["corners"][0]["linked"]["lockup"]
    assert link["measured"] is True
    assert link["laps_with"] == 3 and link["laps_without"] == 3
    assert link["delta_s"] > 0, "the laps that locked were slower through the corner"
    billed = sum(a["at_stake_s"] for a in p["aspects"].values())
    assert p["theoretical_gap_s"] == pytest.approx(billed, abs=1e-3)


def test_a_throttle_lift_is_counted():
    specs = [dict(BASE, lift=(i % 2 == 0)) for i in range(6)]
    s, p = _payload(specs)
    lifts = p["corners"][0]["metrics"]["exit_lifts"]["per_lap"]
    assert sorted(set(lifts.values())) == [0, 1]


def test_line_offsets_are_read_at_the_exit():
    specs = [dict(BASE, wide=w) for w in (0.0, 0.5, 1.0, 1.5, 2.0)]
    s, p = _payload(specs)
    ex = p["corners"][0]["metrics"].get("offset_exit_m")
    assert ex is not None
    vals = [ex["per_lap"][str(n)] for n in _clean_numbers(s)]
    assert max(vals) - min(vals) > 0.5


def test_too_few_clean_laps_is_an_honest_absence():
    p = driving_aspects.compute(_session([BASE, BASE, BASE]))
    assert p["insufficient_data"] is True
    assert "at least 4" in p["reason"]


def test_second_best_not_best_sets_the_target():
    s, p = _payload([dict(BASE, vmin=v) for v in (24.0, 24.2, 24.4, 24.6, 30.0)])
    z = p["corners"][0]["zones"]["rotation"]
    assert z["at_stake_s"] == pytest.approx(z["typical_s"] - z["second_best_s"], abs=1e-4)
    assert z["second_best_s"] > z["best_s"]


def test_gates_and_thresholds_travel_in_the_payload_and_it_is_json():
    s, p = _payload([BASE] * 4)
    assert p["coach_gates"]["strong_p"] == driving_aspects.COACH_GATES["strong_p"]
    assert p["thresholds"]["brake_on_pct"] == 10.0
    assert json.loads(json.dumps(p)) == p
